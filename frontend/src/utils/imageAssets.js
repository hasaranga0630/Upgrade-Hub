export function getAvatarForName(name) {
  if (!name) return avatarUrls[0];
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = name.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % avatarUrls.length;
  return avatarUrls[index];
}
