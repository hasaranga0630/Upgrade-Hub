export function getProductImage(product) {
  if (product && product.imageUrl && product.imageUrl.trim() !== '') {
    return product.imageUrl;
  }
  const nameLower = ((product && product.name) || '').toLowerCase();
  for (const item of sampleProductImages) {
    if (item.keywords.some((k) => nameLower.includes(k))) {
      return item.localUrl || item.onlineUrl;
    }
  }
  return categoryImages[(product && product.category) || 'Mobile Accessory'] || categoryImages['Mobile Accessory'];
}

export function getProductFallbackImage(product) {
  const nameLower = ((product && product.name) || '').toLowerCase();
  for (const item of sampleProductImages) {
    if (item.keywords.some((k) => nameLower.includes(k))) {
      return item.onlineUrl;
    }
  }
  return categoryOnlineFallbacks[(product && product.category) || 'Mobile Accessory'] || categoryOnlineFallbacks['Mobile Accessory'];
}

